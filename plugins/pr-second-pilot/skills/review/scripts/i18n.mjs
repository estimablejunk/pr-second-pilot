export const SUPPORTED = Object.keys(STRINGS);

/**
 * Словарь для языка. Неизвестный код падает на английский: отчёт на чужом
 * языке лучше, чем отчёт с дырами вместо заголовков.
 */
export function dict(lang) {
  const base = STRINGS.en;
  const chosen = STRINGS[String(lang || "en").slice(0, 2).toLowerCase()] || base;
  return { ...base, ...chosen, st: { ...base.st, ...chosen.st }, fs: { ...base.fs, ...chosen.fs } };
}

export function fmt(template, ...args) {
  let i = 0;
  return String(template).replace(/%s/g, () => String(args[i++] ?? ""));
}
