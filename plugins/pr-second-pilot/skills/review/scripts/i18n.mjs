//
// Промпты ревьюера и исполнителя остаются на одном языке: это инструкции
// модели, и держать их в шести переводах значит обречь пять из них на
// расхождение с шестым. А вот то, что читает человек — отчёт и вердикты, —
// обязано быть на его языке. Иначе `report.language` в конфиге просто врёт.
//
